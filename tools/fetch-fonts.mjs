/* ============================================================
   tools/fetch-fonts.mjs — self-host the two typefaces.
   Pulls the subsets the app actually uses from the Google Fonts CDN
   once, writes them into public/fonts/ and generates src/css/fonts.css
   where every url() is local. After this the app never calls a CDN.

   Fonts: Vazirmatn (Persian/Arabic) and Inter (Latin) — both SIL OFL 1.1,
   see CREDITS.md.  Usage:  node tools/fetch-fonts.mjs
   ============================================================ */
import fs from 'fs';
import path from 'path';

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const API = 'https://fonts.googleapis.com/css2?family=Vazirmatn:wght@400..800&family=Inter:wght@400..800&display=swap';
/* subset comment → local file name, per family */
const WANT = {
  Inter: { latin: 'inter-latin', 'latin-ext': 'inter-latin-ext' },
  Vazirmatn: { arabic: 'vazirmatn-arabic', latin: 'vazirmatn-latin', 'latin-ext': 'vazirmatn-latin-ext' },
};

const outDir = 'public/fonts';
fs.mkdirSync(outDir, { recursive: true });

const css = await (await fetch(API, { headers: { 'User-Agent': UA } })).text();
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)];
const faces = [];
for (const [, subset, body] of blocks) {
  const family = /font-family:\s*'([^']+)'/.exec(body)?.[1];
  const src = /url\((https:[^)]+\.woff2)\)/.exec(body)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim();
  const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1]?.trim();
  const local = WANT[family]?.[subset];
  if (!local || !src) continue;
  const file = `${local}.woff2`;
  const buf = Buffer.from(await (await fetch(src, { headers: { 'User-Agent': UA } })).arrayBuffer());
  fs.writeFileSync(path.join(outDir, file), buf);
  faces.push({ family, subset, file, weight, range, bytes: buf.length });
  console.log(`  ${file.padEnd(26)} ${String(Math.round(buf.length / 1024)).padStart(4)} KB  (${family} · ${subset})`);
}

const cssOut = `/* ============================================================
   Generated by tools/fetch-fonts.mjs — do not edit by hand.
   Self-hosted subsets: no CDN request, works offline.
   Both faces are SIL OFL 1.1 (see CREDITS.md).
   ============================================================ */

${faces.map(f => `/* ${f.family} · ${f.subset} · ${Math.round(f.bytes / 1024)} KB */
@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-weight: ${f.weight || '400 800'};
  font-display: swap;
  src: url('../../public/fonts/${f.file}') format('woff2');
  unicode-range: ${f.range};
}`).join('\n\n')}
`;
fs.writeFileSync('src/css/fonts.css', cssOut);
console.log(`\nwrote src/css/fonts.css (${faces.length} faces) · total ${Math.round(faces.reduce((a, f) => a + f.bytes, 0) / 1024)} KB`);
