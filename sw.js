/* ============================================================
   TicTic — service worker
   Strategy
     · install   precache the whole app shell (list generated by
                 tools/build-sw.mjs — never edited by hand)
     · navigate  network-first, cache fallback (so a fresh version is
                 picked up when online, and the app still opens offline)
     · assets    stale-while-revalidate (instant offline, self-updating)
     · update    a new worker waits; the page offers “Reload” and only
                 then does this one take over (no surprise refresh)
   Cache name carries the version, so activating deletes the previous one.
   ============================================================ */
